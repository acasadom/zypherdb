/// True if `word` (case-folded, accents kept) is in the sorted `list`.
pub fn isStopWord(list: []const []const u8, word: []const u8) bool {
    return std.sort.binarySearch([]const u8, list, word, struct {
        fn order(key: []const u8, item: []const u8) std.math.Order {
            return std.mem.order(u8, key, item);
        }
    }.order) != null;
}
