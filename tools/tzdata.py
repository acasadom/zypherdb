"""Generates vendor/tzdata/ from a wheel of the `tzdata` Python package.

    python3 -I tools/tzdata.py tzdata-<version>-py2.py3-none-any.whl vendor/tzdata
    zig fmt vendor/tzdata/tzdata.zig

The wheel (https://pypi.org/project/tzdata/) holds the IANA time zone database compiled to TZif
files. Writes, into the output directory:

- tzdata.bin: the TZif files, each distinct one once (many names are links to the same zone);
- tzdata.zig: the version, the wheel's SHA-256, and every zone name, sorted, with where its file
  is in tzdata.bin;
- LICENSE, LICENSE_APACHE: the package's licenses (the data itself is in the public domain).

ZypherDB embeds these instead of reading the system's database, so a zone's history is the same
on every machine: Linux distributions build theirs from different sources (Debian's keeps the
pre-1970 history that IANA merged away, for one).
"""

import hashlib
import sys
import zipfile
from pathlib import Path

wheel_path = Path(sys.argv[1])
output = Path(sys.argv[2])
wheel_bytes = wheel_path.read_bytes()
digest = hashlib.sha256(wheel_bytes).hexdigest()

prefix = "tzdata/zoneinfo/"
zones = {}
version = None
licenses = {}
with zipfile.ZipFile(wheel_path) as wheel:
    for entry in wheel.namelist():
        if entry.endswith("/METADATA") and ".dist-info/" in entry:
            for line in wheel.read(entry).decode().splitlines():
                if line.startswith("Version: "):
                    version = line.removeprefix("Version: ")
        elif entry.endswith(".dist-info/licenses/LICENSE") or entry.endswith(".dist-info/LICENSE"):
            licenses["LICENSE"] = wheel.read(entry)
        elif entry.endswith("licenses/LICENSE_APACHE"):
            licenses["LICENSE_APACHE"] = wheel.read(entry)
        elif entry.startswith(prefix) and not entry.endswith("/"):
            data = wheel.read(entry)
            if data[:4] == b"TZif":  # skips __init__.py, the .tab and .zi files, leapseconds
                zones[entry.removeprefix(prefix)] = data

if version is None or not zones:
    sys.exit(f"{wheel_path}: not a tzdata wheel")
for name in ("LICENSE", "LICENSE_APACHE"):
    if name not in licenses:
        sys.exit(f"{wheel_path}: no {name}")

blob = bytearray()
start_of = {}
entries = []
for name in sorted(zones):
    data = zones[name]
    if data not in start_of:
        start_of[data] = len(blob)
        blob.extend(data)
    entries.append((name, start_of[data], len(data)))

output.mkdir(parents=True, exist_ok=True)
(output / "tzdata.bin").write_bytes(bytes(blob))
for name, text in licenses.items():
    (output / name).write_bytes(text)
with open(output / "tzdata.zig", "w") as out:
    out.write(f"//! The IANA time zone database {version}, from the tzdata Python package\n")
    out.write(f"//! (wheel SHA-256 {digest}).\n")
    out.write("//! Generated by tools/tzdata.py: do not edit.\n\n")
    out.write(f'pub const version = "{version}";\n\n')
    out.write("/// The TZif files, each distinct one once.\n")
    out.write('pub const bytes = @embedFile("tzdata.bin");\n\n')
    out.write("/// A zone name and where its TZif file is in `bytes`.\n")
    out.write("pub const Zone = struct { name: []const u8, start: u32, length: u32 };\n\n")
    out.write("/// Every zone, sorted by name (byte order).\n")
    out.write("pub const zones = [_]Zone{\n")
    for name, start, length in entries:
        out.write(f'    .{{ .name = "{name}", .start = {start}, .length = {length} }},\n')
    out.write("};\n")
print(f"tzdata {version}: {len(entries)} zones, {len(start_of)} distinct files, {len(blob)} bytes", file=sys.stderr)
