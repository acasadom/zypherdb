"""Generates src/text/unicode_tables.zig from the Unicode Character Database.

    python3 tools/unicode_tables.py UCD_DIR | zig fmt --stdin > src/text/unicode_tables.zig

(zig fmt aligns the tables' columns, as CI's formatting check expects.)

UCD_DIR holds UnicodeData.txt, CaseFolding.txt and SpecialCasing.txt of one Unicode version
(https://www.unicode.org/Public/<version>/ucd/). The tables are data under
the Unicode License v3 (https://www.unicode.org/license.txt).

Five tables: three for full-text search,

- word_ranges: the code points that make up words: letters (L*), numbers
  (N*) and marks (M*), as sorted inclusive ranges.
- fold: a code point's search form, when it differs from the code point:
  full case folding (C + F), compatibility decomposition (NFKD), marks
  removed, and case folding again. So "Contención" and "CONTENCION" fold
  alike, "Straße" folds to "strasse", "ﬁ" to "fi". A mark folds to nothing.
- case_fold: full case folding alone (C + F), accents kept: what stemmers
  work on, since their rules know accented letters.

and two for toUpper() and toLower():

- upper, lower: the full case mappings (UnicodeData's simple mappings, and
  SpecialCasing's unconditional ones, so "ß" upper-cases to "SS").
"""

import sys
from pathlib import Path

ucd = Path(sys.argv[1])
version = (ucd / "version.txt").read_text(encoding="utf-8").strip() if (ucd / "version.txt").exists() else "16.0.0"

categories = {}
decompositions = {}
simple_upper = {}
simple_lower = {}
lines = (ucd / "UnicodeData.txt").read_text(encoding="utf-8").splitlines()
index = 0
while index < len(lines):
    fields = lines[index].split(";")
    code, name, category, decomposition = int(fields[0], 16), fields[1], fields[2], fields[5]
    if name.endswith(", First>"):
        last = int(lines[index + 1].split(";")[0], 16)
        for c in range(code, last + 1):
            categories[c] = category
        index += 2
        continue
    categories[code] = category
    if fields[12]:
        simple_upper[code] = [int(fields[12], 16)]
    if fields[13]:
        simple_lower[code] = [int(fields[13], 16)]
    if decomposition:
        parts = decomposition.split()
        if parts[0].startswith("<"):
            parts = parts[1:]  # compatibility tag: decompose anyway (NFKD)
        decompositions[code] = [int(p, 16) for p in parts]
    index += 1

case_folding = {}
for line in (ucd / "CaseFolding.txt").read_text(encoding="utf-8").splitlines():
    line = line.split("#")[0].strip()
    if not line:
        continue
    code, status, mapping = [f.strip() for f in line.split(";")[:3]]
    if status in ("C", "F"):
        case_folding[int(code, 16)] = [int(p, 16) for p in mapping.split()]


special_lower = {}
special_upper = {}
for line in (ucd / "SpecialCasing.txt").read_text(encoding="utf-8").splitlines():
    line = line.split("#")[0].strip()
    if not line:
        continue
    fields = [f.strip() for f in line.split(";")]
    if fields[4]:
        continue  # a conditional mapping (a language, or final sigma): not table data
    code = int(fields[0], 16)
    special_lower[code] = [int(p, 16) for p in fields[1].split()]
    special_upper[code] = [int(p, 16) for p in fields[3].split()]


def full_mapping(simple, special):
    codes = set(simple) | set(special)
    mapping = {c: special.get(c, simple.get(c, [c])) for c in codes}
    return sorted((c, m) for c, m in mapping.items() if m != [c])


def fold_case(codes):
    return [m for c in codes for m in case_folding.get(c, [c])]


def decompose(code):
    if code not in decompositions:
        return [code]
    return [d for part in decompositions[code] for d in decompose(part)]


def is_mark(code):
    return categories.get(code, "Cn").startswith("M")


def search_form(code):
    codes = fold_case([code])
    codes = [d for c in codes for d in decompose(c)]
    codes = [c for c in codes if not is_mark(c)]
    return fold_case(codes)


def is_word(code):
    return categories.get(code, "Cn")[0] in "LNM"


ranges = []
for code in range(0x110000):
    if not is_word(code):
        continue
    if ranges and ranges[-1][1] == code - 1:
        ranges[-1][1] = code
    else:
        ranges.append([code, code])

folds = []
for code in sorted(c for c in categories if is_word(c) or c in case_folding):
    form = search_form(code)
    if form != [code]:
        folds.append((code, form))

out = sys.stdout
out.write(f"//! Generated by tools/unicode_tables.py from the Unicode Character Database {version}.\n")
out.write("//! Do not edit. Data under the Unicode License v3 (https://www.unicode.org/license.txt).\n\n")
out.write(f"pub const unicode_version = \"{version}\";\n\n")
out.write("/// Code points that make up words (letters, numbers, marks): sorted inclusive ranges.\n")
out.write("pub const word_ranges = [_][2]u21{\n")
for start, end in ranges:
    out.write(f"    .{{ 0x{start:X}, 0x{end:X} }},\n")
out.write("};\n\n")
out.write("/// The code points whose search form differs from them, sorted; the form of\n")
out.write("/// `fold_keys[i]` is `fold_data[fold_starts[i]..fold_starts[i + 1]]`.\n")
out.write("pub const fold_keys = [_]u21{\n")
for i in range(0, len(folds), 12):
    out.write("    " + " ".join(f"0x{c:X}," for c, _ in folds[i:i + 12]) + "\n")
out.write("};\n\n")
starts = [0]
data = []
for _, form in folds:
    data.extend(form)
    starts.append(len(data))
out.write("pub const fold_starts = [_]u32{\n")
for i in range(0, len(starts), 16):
    out.write("    " + " ".join(f"{s}," for s in starts[i:i + 16]) + "\n")
out.write("};\n\n")
out.write("pub const fold_data = [_]u21{\n")
for i in range(0, len(data), 12):
    out.write("    " + " ".join(f"0x{c:X}," for c in data[i:i + 12]) + "\n")
out.write("};\n\n")


def write_mapping(prefix, mappings, doc):
    """A code point -> code points table: `<prefix>_keys`, `<prefix>_starts`, `<prefix>_data`."""
    for line in doc:
        out.write(f"/// {line}\n")
    out.write(f"pub const {prefix}_keys = [_]u21{{\n")
    for i in range(0, len(mappings), 12):
        out.write("    " + " ".join(f"0x{c:X}," for c, _ in mappings[i:i + 12]) + "\n")
    out.write("};\n\n")
    starts = [0]
    data = []
    for _, mapping in mappings:
        data.extend(mapping)
        starts.append(len(data))
    out.write(f"pub const {prefix}_starts = [_]u32{{\n")
    for i in range(0, len(starts), 16):
        out.write("    " + " ".join(f"{s}," for s in starts[i:i + 16]) + "\n")
    out.write("};\n\n")
    out.write(f"pub const {prefix}_data = [_]u21{{\n")
    for i in range(0, len(data), 12):
        out.write("    " + " ".join(f"0x{c:X}," for c in data[i:i + 12]) + "\n")
    out.write("};\n")


write_mapping("case", sorted((c, m) for c, m in case_folding.items() if m != [c]), [
    "Full case folding (C + F), accents kept: the form of `case_keys[i]` is",
    "`case_data[case_starts[i]..case_starts[i + 1]]`.",
])
out.write("\n")
write_mapping("upper", full_mapping(simple_upper, special_upper), [
    "Full upper-case mappings, laid out as the case folding table.",
])
out.write("\n")
write_mapping("lower", full_mapping(simple_lower, special_lower), [
    "Full lower-case mappings, laid out as the case folding table.",
])
print(f"{len(ranges)} word ranges, {len(folds)} folds, {len(data)} folded code points", file=sys.stderr)
